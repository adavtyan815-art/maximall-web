const n = (v: unknown) => (typeof v === 'number' && Number.isFinite(v) ? v.toLocaleString('en-US', { maximumFractionDigits: 2 }) : String(v ?? ''));
const byn = (v: unknown) => `${n(v)} BYN`;
/** Designer terminology (2026-10-07): a pending price next to a number is «≈ 410 BYN (estimate)»; alone «price to be confirmed». */
