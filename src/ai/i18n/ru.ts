function obstacleRu(o: string): string {
  const k = o.toUpperCase();
  return k === 'OPENING' ? 'проём' : k === 'WINDOW' ? 'окно' : k === 'DOOR' ? 'дверной проём' : k === 'SET' ? 'другой комплект' : k === 'WALL' ? 'стена' : k === 'OBSTACLE' ? 'препятствие' : o;
}
function partRu(p: string): string {
  return ({ cabinet: 'тумба', closet: 'навесной шкаф', countertop: 'столешница', sink: 'раковина', faucet: 'смеситель', mirror: 'зеркало', doors: 'дверцы' } as Record<string, string>)[p] ?? p;
}
